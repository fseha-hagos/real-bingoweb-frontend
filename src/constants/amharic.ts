export function translateTransactionStatus(status: string): string {
  const key = (status || "").toLowerCase();
  const map: Record<string, string> = {
    completed: am.completed,
    pending: am.pending,
    failed: am.failed,
    approved: am.completed,
    rejected: am.failed,
    cancelled: am.failed,
  };
  return map[key] ?? status;
}

export function formatBirr(amount: number): string {
  return `${am.birr} ${Number(amount || 0).toLocaleString("am-ET", {
    maximumFractionDigits: 2,
  })}`;
}
